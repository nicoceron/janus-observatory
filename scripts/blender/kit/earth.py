def chaikin(loop, passes=2):
    """Corner cutting: turns a hand-drawn polygon into a smooth coast."""
    pts = [np.array(p, dtype=float) for p in loop]
    for _ in range(passes):
        out = []
        n = len(pts)
        for i in range(n):
            a, b = pts[i], pts[(i + 1) % n]
            out.append(a * 0.75 + b * 0.25)
            out.append(a * 0.25 + b * 0.75)
        pts = out
    return np.array(pts)


def unit(lat, lon):
    lat, lon = np.radians(lat), np.radians(lon)
    return np.stack([np.cos(lat) * np.cos(lon), np.cos(lat) * np.sin(lon), np.sin(lat)], axis=-1)


def segment_distance(points, a, b):
    """Angular distance in degrees from unit points (N, 3) to the great-circle arc a-b."""
    normal = np.cross(a, b)
    length = np.linalg.norm(normal)
    da = np.degrees(np.arccos(np.clip(points @ a, -1, 1)))
    db = np.degrees(np.arccos(np.clip(points @ b, -1, 1)))
    ends = np.minimum(da, db)
    if length < 1e-9:
        return ends
    normal = normal / length
    along = points - np.outer(points @ normal, normal)
    # Inside the arc when the projection lies between a and b.
    inside = (np.cross(a, along) @ normal >= 0) & (np.cross(along, b) @ normal >= 0)
    plane = np.degrees(np.arcsin(np.clip(np.abs(points @ normal), 0, 1)))
    return np.where(inside, plane, ends)


def inside_polygon(lat, lon, loop):
    """Even-odd test in (longitude, latitude); `loop` is (lat, lon) and may pass 180."""
    result = np.zeros(lat.shape, dtype=bool)
    ys, xs = loop[:, 0], loop[:, 1]
    for shift in (0.0, 360.0):
        x = lon + shift
        hit = np.zeros(lat.shape, dtype=bool)
        n = len(loop)
        for i in range(n):
            x0, y0, x1, y1 = xs[i], ys[i], xs[(i + 1) % n], ys[(i + 1) % n]
            if y0 == y1:
                continue
            crosses = (y0 > lat) != (y1 > lat)
            at = x0 + (lat - y0) / (y1 - y0) * (x1 - x0)
            hit ^= crosses & (x < at)
        result |= hit
    return result


def loop_field(lat, lon, points, loop):
    """Signed distance in degrees to one closed coast: positive inside."""
    smooth = chaikin(loop)
    vectors = unit(smooth[:, 0], smooth[:, 1])
    distance = np.full(lat.shape, 1e9)
    for i in range(len(vectors)):
        distance = np.minimum(distance, segment_distance(points, vectors[i], vectors[(i + 1) % len(vectors)]))
    return np.where(inside_polygon(lat, lon, smooth), distance, -distance)


def polyline_field(points, line, width):
    vectors = unit(np.array([p[0] for p in line]), np.array([p[1] for p in line]))
    distance = np.full(points.shape[0], 1e9)
    for a, b in zip(vectors, vectors[1:]):
        distance = np.minimum(distance, segment_distance(points, a, b))
    t = np.clip(1 - distance / width, 0, 1)
    return t * t * (3 - 2 * t)


def patch_field(points, patches):
    out = np.zeros(points.shape[0])
    for lat, lon, radius, strength in patches:
        centre = unit(np.array(lat), np.array(lon))
        distance = np.degrees(np.arccos(np.clip(points @ centre, -1, 1)))
        t = np.clip(1 - distance / radius, 0, 1)
        out = np.maximum(out, t * t * (3 - 2 * t) * strength)
    return out


WIDTH, HEIGHT = 360, 180
LIMIT = 16.0


def fields():
    lats = -89.5 + np.arange(HEIGHT)
    lons = -179.5 + np.arange(WIDTH)
    lon, lat = np.meshgrid(lons, lats)
    lat, lon = lat.ravel(), lon.ravel()
    points = unit(lat, lon)

    land = np.full(lat.shape, -1e9)
    for loop in LAND:
        land = np.maximum(land, loop_field(lat, lon, points, loop))
    # Antarctica: everything south of a coast latitude that varies with longitude.
    coast = np.interp(lon, [p[0] for p in ANTARCTIC_COAST], [p[1] for p in ANTARCTIC_COAST])
    land = np.maximum(land, coast - lat)
    for loop in WATER:
        land = np.minimum(land, -loop_field(lat, lon, points, loop))
    land = np.clip(land, -LIMIT, LIMIT)

    ranges = np.zeros(lat.shape)
    for line, width, strength in RANGES:
        ranges = np.maximum(ranges, polyline_field(points, line, width) * strength)
    dry = patch_field(points, DRY)
    lush = patch_field(points, LUSH)
    shape = (HEIGHT, WIDTH)
    return {
        "land": land.reshape(shape),
        "range": ranges.reshape(shape),
        "dry": dry.reshape(shape),
        "lush": lush.reshape(shape),
    }


def encode() -> tuple[bytes, dict]:
    """The four fields as unsigned bytes, channel after channel, with their decoding ranges."""
    f = fields()
    land = np.round((f["land"] + LIMIT) / (2 * LIMIT) * 255).astype(np.uint8)
    rest = [np.round(np.clip(f[name], 0, 1) * 255).astype(np.uint8) for name in ("range", "dry", "lush")]
    data = b"".join(channel.tobytes() for channel in [land, *rest])
    meta = {
        "width": WIDTH,
        "height": HEIGHT,
        "channels": ["land", "range", "dry", "lush"],
        "landLimit": LIMIT,
    }
    return data, meta
