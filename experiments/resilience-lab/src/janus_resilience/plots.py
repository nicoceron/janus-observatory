"""Figure generation for the resilience-lab experiment.

Every figure is rendered from generated artifacts (reports and datasets produced by the
CLI commands) or recomputed deterministically from seeded ensembles, so any figure can
be regenerated byte-stable from the pinned configuration. Figures are written to
reports/figures/ as PNG at 150 dpi; the underlying numbers always live in the JSON
reports, which remain the citable artifacts.

matplotlib is an optional dev dependency: this module is imported only by the
`figures` CLI command.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from .analytics import expected_metrics
from .dataset import DESIGN_SPACE, PARAM_ORDER
from .event_sim import simulate_events
from .params import load_anchors, sample_perturbed
from .reference_sim import simulate_reference
from .surrogate import load_dataset
from .survival import aalen_johansen, kaplan_meier

FIGURES_DIR = Path(__file__).resolve().parents[2] / "reports" / "figures"
REPORTS_DIR = Path(__file__).resolve().parents[2] / "reports"
GENERATED_DIR = Path(__file__).resolve().parents[2] / "data" / "generated"

SCENARIO_IDS = [f"S{i}" for i in range(1, 11)]
SCENARIO_COLORS = {sid: plt.cm.tab10(i) for i, sid in enumerate(SCENARIO_IDS)}

plt.rcParams.update(
    {
        "figure.dpi": 110,
        "savefig.dpi": 150,
        "font.size": 10,
        "axes.titlesize": 11,
        "axes.grid": True,
        "grid.alpha": 0.25,
        "axes.spines.top": False,
        "axes.spines.right": False,
        "legend.frameon": False,
    }
)


def _save(fig, name: str) -> Path:
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    path = FIGURES_DIR / name
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)
    print(f"wrote {path}")
    return path


def _scenario_ensemble(sid: str, n: int = 4000, seed_offset: int = 17):
    base = load_anchors()[sid]
    draws = sample_perturbed(base, n, np.random.default_rng(12345 + seed_offset))
    outcomes = simulate_events(draws, window=1000)
    return outcomes


def fig_trajectories() -> Path:
    """Paper Figure 1 analog: ensemble technology and resource trajectories."""
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.5), sharex=True)
    years = np.arange(1, 1001)
    for sid in SCENARIO_IDS:
        base = load_anchors()[sid]
        draws = sample_perturbed(base, 200, np.random.default_rng(12345))
        out = simulate_reference(draws, seed=12345, record_trajectories=True)
        t_mean = out.trajectories_T.mean(axis=0)
        t_std = out.trajectories_T.std(axis=0)
        r_mean = out.trajectories_R.mean(axis=0)
        r_std = out.trajectories_R.std(axis=0)
        color = SCENARIO_COLORS[sid]
        for ax, mean, std in ((axes[0], t_mean, t_std), (axes[1], r_mean, r_std)):
            ax.plot(years, mean, color=color, lw=1.6, label=sid)
            ax.fill_between(years, mean - std, mean + std, color=color, alpha=0.15, lw=0)
    axes[0].set_title("Technological capacity T(t)")
    axes[1].set_title("Resource stock R(t)")
    for ax in axes:
        ax.set_xlabel("year")
        ax.set_xlim(0, 1000)
    axes[0].set_ylabel("model units (T0 = 1)")
    axes[1].set_ylabel("model resource units")
    axes[0].legend(ncol=2, fontsize=8, loc="upper left")
    fig.suptitle(
        "Independent reimplementation - 200-run ensembles, Table 5 perturbations",
        fontsize=10,
        y=1.02,
    )
    return _save(fig, "fig-trajectories.png")


def fig_replication() -> Path:
    """Ours vs reported aggregates with validation tolerances."""
    report = json.loads((REPORTS_DIR / "replication-report.json").read_text(encoding="utf-8"))
    metrics = [
        ("mean_duty_cycle", "Mean duty cycle"),
        ("mean_collapse_count", "Mean collapse count"),
        ("mean_time_to_first_collapse", "Mean first-collapse year"),
        ("fraction_never_collapsed", "Fraction never collapsed"),
    ]
    fig, axes = plt.subplots(2, 2, figsize=(9.5, 9))
    for ax, (key, label) in zip(axes.flat, metrics, strict=True):
        xs, ys, errs, sids = [], [], [], []
        for scenario in report["scenarios"]:
            comparison = next(c for c in scenario["comparisons"] if c["metric"] == key)
            if comparison.get("reported") is None or comparison.get("ours") is None:
                continue
            xs.append(comparison["reported"])
            ys.append(comparison["ours"])
            errs.append(comparison.get("tolerance") or 0.0)
            sids.append(scenario["scenarioId"])
        xs, ys, errs = np.array(xs), np.array(ys), np.array(errs)
        span = max(xs.max(), ys.max()) * 1.08 + 1e-9
        ax.fill_between([0, span], [0, span * 0.95], [0, span * 1.05], color="0.85", zorder=0)
        ax.plot([0, span], [0, span], color="0.3", lw=0.8, ls="--", zorder=1)
        ax.errorbar(
            xs, ys, yerr=errs, fmt="none", ecolor="0.55", elinewidth=1.2, capsize=3, zorder=2
        )
        ax.scatter(xs, ys, c=[SCENARIO_COLORS[s] for s in sids], s=42, zorder=3)
        for x, y, sid in zip(xs, ys, sids, strict=True):
            ax.annotate(sid, (x, y), textcoords="offset points", xytext=(5, 3), fontsize=7.5)
        ax.set_title(label)
        ax.set_xlim(0, span)
        ax.set_ylim(0, span)
        ax.set_aspect("equal")
    fig.supxlabel("value reported by JANUS-PAPER-05")
    fig.supylabel("value from independent reimplementation")
    fig.suptitle(
        "Replication of reported Monte Carlo aggregates (band = validation tolerance)",
        fontsize=10,
    )
    fig.tight_layout()
    return _save(fig, "fig-replication.png")


def fig_survival() -> Path:
    """Kaplan-Meier curves and cause-specific cumulative incidence."""
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.5))
    for sid in SCENARIO_IDS:
        outcomes = _scenario_ensemble(sid)
        event = ~outcomes.censored
        km = kaplan_meier(outcomes.first_collapse_year, event)
        aj = aalen_johansen(outcomes.first_collapse_year, event, outcomes.first_cause.astype(str))
        color = SCENARIO_COLORS[sid]
        axes[0].step(km.times, km.survival, where="post", color=color, lw=1.5, label=sid)
        if sid == "S1":
            axes[1].plot(aj.times, aj.cif_hazard, color=color, lw=1.8, label="S1 hazard")
            axes[1].plot(
                aj.times, aj.cif_resource, color=color, lw=1.2, ls="--", label="S1 resource"
            )
        elif sid == "S6":
            axes[1].plot(aj.times, aj.cif_hazard, color=color, lw=1.8, label="S6 hazard")
            axes[1].plot(
                aj.times, aj.cif_resource, color=color, lw=1.2, ls="--", label="S6 resource"
            )
        elif sid == "S4":
            axes[1].plot(aj.times, aj.cif_resource, color=color, lw=1.8, label="S4 resource")
            axes[1].plot(aj.times, aj.cif_hazard, color=color, lw=1.0, ls="--", label="S4 hazard")
    axes[0].set_title("Kaplan-Meier: collapse-free survival")
    axes[0].set_xlabel("year")
    axes[0].set_ylabel("P(no first collapse yet)")
    axes[0].set_ylim(-0.02, 1.02)
    axes[0].legend(ncol=2, fontsize=8)
    axes[1].set_title("Aalen-Johansen cumulative incidence by cause")
    axes[1].set_xlabel("year")
    axes[1].set_ylabel("cumulative incidence")
    axes[1].legend(fontsize=8, loc="lower right")
    fig.suptitle(
        "Never-collapsed runs are right-censored at year 1000 (20k-run ensembles)",
        fontsize=10,
        y=1.02,
    )
    fig.tight_layout()
    return _save(fig, "fig-survival.png")


def fig_duty_distributions() -> Path:
    """Run-level duty-cycle distribution per scenario."""
    fig, ax = plt.subplots(figsize=(10, 4.2))
    rng = np.random.default_rng(3)
    for i, sid in enumerate(SCENARIO_IDS):
        outcomes = _scenario_ensemble(sid)
        duty = np.sort(outcomes.duty_cycle)
        jitter = rng.uniform(-0.18, 0.18, size=duty.size)
        ax.scatter(
            np.full(duty.size, i) + jitter, duty, s=2, alpha=0.25, color=SCENARIO_COLORS[sid]
        )
        q1, med, q3 = np.percentile(duty, [25, 50, 75])
        ax.vlines(i, q1, q3, color="black", lw=3, zorder=3)
        ax.scatter([i], [med], marker="_", s=220, color="white", edgecolor="black", zorder=4)
    ax.set_xticks(range(len(SCENARIO_IDS)), SCENARIO_IDS)
    ax.set_ylabel("run duty cycle")
    ax.set_title("Duty-cycle distributions per scenario (each dot = 1 of 4,000 runs)")
    return _save(fig, "fig-duty-distributions.png")


def fig_sensitivity() -> Path:
    """Total-order Sobol indices with standard errors plus Morris ranking."""
    report = json.loads((REPORTS_DIR / "sensitivity-report.json").read_text(encoding="utf-8"))
    sobol = report["sobol"]
    names = list(sobol["analytic_expected_duty_cycle"])
    x = np.arange(len(names))
    width = 0.27

    fig, axes = plt.subplots(1, 2, figsize=(12.5, 4.4))

    def se(entry, key):
        value = entry.get(key)
        return 0.0 if value is None else value

    for k, (out_key, label) in enumerate(
        [
            ("analytic_expected_duty_cycle", "analytic duty cycle"),
            ("simulated_duty_cycle_crn", "simulated duty cycle (CRN)"),
            ("analytic_expected_collapses", "analytic collapse count"),
        ]
    ):
        entries = sobol[out_key]
        values = [entries[n]["total_order"] for n in names]
        errors = [se(entries[n], "total_order_se") for n in names]
        axes[0].bar(x + (k - 1) * width, values, width * 0.92, yerr=errors, capsize=2, label=label)
    axes[0].set_xticks(x, names)
    axes[0].set_ylabel("total-order Sobol index ST")
    axes[0].set_title(
        f"Sobol total-order indices ({report['baseSamples']} base x "
        f"{report['sobolReplicates']} replicates)"
    )
    axes[0].legend(fontsize=8)

    morris = report["morris_analytic_duty"]
    order = sorted(names, key=lambda n: morris[n]["mu_star"])
    axes[1].barh(
        range(len(order)),
        [morris[n]["mu_star"] for n in order],
        color="0.35",
    )
    axes[1].set_yticks(range(len(order)), order)
    axes[1].set_xlabel("Morris mu* (unit cube)")
    axes[1].set_title("Elementary-effect magnitude, duty cycle")
    fig.tight_layout()
    return _save(fig, "fig-sensitivity.png")


def fig_surrogate() -> Path:
    """Benchmark degradation under grouped holdouts."""
    report = json.loads((REPORTS_DIR / "surrogate-benchmark.json").read_text(encoding="utf-8"))
    rows = [r for r in report["results"] if r["target"] == "duty_cycle"]
    models = [
        "analytic_renewal",
        "hist_gradient_boosting",
        "ridge_quadratic",
        "gaussian_process_rbf",
    ]
    protocols = ["random", "region_block", "anchor_out"]
    protocol_labels = ["random", "region block", "anchor out"]
    lookup = {(r["protocol"], r["model"]): r for r in rows}

    fig, axes = plt.subplots(1, 2, figsize=(12.5, 4.4))
    x = np.arange(len(models))
    width = 0.26
    for k, protocol in enumerate(protocols):
        values = [lookup[(protocol, m)]["point_r2"] for m in models]
        axes[0].bar(x + (k - 1) * width, values, width * 0.92, label=protocol_labels[k])
        coverage = [lookup[(protocol, m)]["coverage90"] for m in models]
        axes[1].bar(x + (k - 1) * width, coverage, width * 0.92, label=protocol_labels[k])
    axes[1].axhline(0.90, color="crimson", lw=1, ls="--")
    axes[1].text(len(models) - 0.5, 0.905, "nominal 90%", color="crimson", fontsize=8, ha="right")
    labels = ["analytic\nrenewal", "hist grad\nboosting", "ridge\n(quadratic)", "gaussian\nprocess"]
    for ax, title, ylim in (
        (axes[0], "Duty-cycle prediction, point-level R2", None),
        (axes[1], "Split-conformal empirical coverage (nominal 0.90)", (0.0, 1.05)),
    ):
        ax.set_xticks(x, labels, fontsize=9)
        ax.set_title(title)
        if ylim:
            ax.set_ylim(*ylim)
    axes[0].set_ylabel("point-level R2")
    axes[0].axhline(0.0, color="0.2", lw=0.8)
    axes[0].legend(fontsize=8)
    axes[1].legend(fontsize=8, loc="lower left")
    fig.tight_layout()
    return _save(fig, "fig-surrogate.png")


def fig_dataset_map() -> Path:
    """Design-space map: point-mean duty cycle over the depletion-recovery plane."""
    dataset_files = sorted(GENERATED_DIR.glob("janus-resilience-level2-*.csv.gz"))
    if not dataset_files:
        raise FileNotFoundError("generate the dataset first: janus-resilience dataset")
    data = load_dataset(dataset_files[-1])
    delta_col = PARAM_ORDER.index("delta")
    rf_col = PARAM_ORDER.index("rf")

    from .surrogate import analytic_baseline

    points = np.unique(data.point_id)
    point_delta = np.array([data.features[data.point_id == p][:, delta_col].mean() for p in points])
    point_rf = np.array([data.features[data.point_id == p][:, rf_col].mean() for p in points])
    point_duty = np.array(
        [
            analytic_baseline(data.features[data.point_id == p], "duty_cycle").mean()
            for p in points
        ]
    )

    fig, ax = plt.subplots(figsize=(8.6, 4.8))
    hb = ax.hexbin(point_delta, point_rf, C=point_duty, gridsize=16, cmap="viridis", mincnt=6)
    cb = fig.colorbar(hb, ax=ax)
    cb.set_label("expected duty cycle per design point")
    anchors = load_anchors()
    for sid, anchor in anchors.items():
        if DESIGN_SPACE["delta"][0] <= anchor.delta <= DESIGN_SPACE["delta"][1]:
            ax.scatter(
                anchor.delta, anchor.rf, marker="*", s=170, color="white",
                edgecolor="black", zorder=4,
            )
            ax.annotate(
                sid,
                (anchor.delta, anchor.rf),
                xytext=(5, 4),
                textcoords="offset points",
                fontsize=8,
            )
    ax.set_xlabel("resource depletion rate delta")
    ax.set_ylabel("recovery fraction rf")
    ax.set_title(
        "Level-2 dataset: exact expected duty cycle per design point\n"
        "(marginalised over the other five parameters)"
    )
    return _save(fig, "fig-dataset-map.png")


def fig_regime_boundary() -> Path:
    """Analytic expected collapse count across the rf-delta plane at S8 settings."""
    rf_grid = np.linspace(0.05, 1.0, 120)
    delta_grid = np.linspace(0.1, 2.5, 120)
    counts = np.zeros((delta_grid.size, rf_grid.size))
    for i, delta in enumerate(delta_grid):
        for j, rf in enumerate(rf_grid):
            counts[i, j] = expected_metrics(
                r0=800.0, delta=float(delta), h=0.0, rd=70, rf=float(rf)
            ).expected_collapses
    fig, ax = plt.subplots(figsize=(8.0, 4.6))
    mesh = ax.pcolormesh(rf_grid, delta_grid, counts, cmap="magma", shading="auto")
    contour = ax.contour(
        rf_grid, delta_grid, counts, levels=[1, 2, 3, 4, 5], colors="white", linewidths=0.8
    )
    ax.clabel(contour, fmt="%d", fontsize=7)
    anchor = load_anchors()["S8"]
    ax.scatter(
        anchor.rf, anchor.delta, marker="*", s=200, color="cyan", edgecolor="black", zorder=5
    )
    ax.annotate(
        "S8 baseline",
        (anchor.rf, anchor.delta),
        xytext=(6, 5),
        textcoords="offset points",
        fontsize=8,
    )
    cb = fig.colorbar(mesh, ax=ax)
    cb.set_label("expected collapses within 1,000 yr (exact renewal recursions)")
    ax.set_xlabel("recovery fraction rf")
    ax.set_ylabel("depletion rate delta")
    ax.set_title("Regime structure of oscillation count (S8: R0=800, rd=70, h=0)")
    return _save(fig, "fig-regime-boundary.png")


def fig_persistence() -> Path:
    """Observation probabilities from paper Eq. 7 with reimplemented duty cycles."""
    report = json.loads((REPORTS_DIR / "persistence-report.json").read_text(encoding="utf-8"))
    rows = report["usingReimplementedDutyCycles"]["rows"]
    signatures = [("no2", "NO2 (~days)"), ("cfc11", "CFC-11 (55 yr)"), ("cfc12", "CFC-12 (140 yr)")]
    x = np.arange(len(rows))
    width = 0.26
    fig, ax = plt.subplots(figsize=(10.5, 4.2))
    for k, (sig, label) in enumerate(signatures):
        values = [row[sig] if row[sig] is not None else 0.0 for row in rows]
        ax.bar(x + (k - 1) * width, values, width * 0.92, label=label)
    ax.set_xticks(x, [row["scenarioId"] for row in rows])
    ax.set_ylabel("p_i (Eq. 7)")
    ax.set_ylim(0, 1.05)
    ax.set_title("Probability a technosignature overlaps a 1,000-year observing window")
    ax.legend(fontsize=8)
    return _save(fig, "fig-persistence.png")


